"""News / RSS collection.

Covers regular RSS feeds AND Google News *search* feeds (URLs generated by the wizard).
Key behaviours required by the spec:
  * date-range injection (after:/before:) with monthly/weekly chunking to beat the
    ~100-results-per-query cap;
  * comma-separated OR keyword filter;
  * strict relevance validation (headline match keeps; otherwise fetch body, strip
    related-articles/boilerplate BEFORE checking, drop if no term in real content,
    store fetched paragraphs as the item text);
  * first-paragraph fetch when a feed summary merely repeats the title;
  * best-effort Google News redirect resolution;
  * per-feed health check.

Regular RSS cannot reach back in time — only chunked Google News (and GDELT) can. This
limitation is documented in the export Methodology.
"""
from __future__ import annotations

import calendar
from datetime import date, datetime, timedelta
from typing import Any, Callable, Dict, List, Optional
from urllib.parse import parse_qs, quote_plus, urlparse, urlunparse

from scrapers import relevance
from scrapers.base import ScrapeResult, relevance_terms

CHANNEL = "news"


# --------------------------------------------------------------------------- #
# Pure helpers (unit-tested without network)
# --------------------------------------------------------------------------- #
def _as_date(d) -> date:
    if isinstance(d, datetime):
        return d.date()
    if isinstance(d, date):
        return d
    return datetime.strptime(str(d)[:10], "%Y-%m-%d").date()


def _first_of_next_month(d: date) -> date:
    if d.month == 12:
        return date(d.year + 1, 1, 1)
    return date(d.year, d.month + 1, 1)


def chunk_date_ranges(start, end, mode: str = "monthly") -> List[Dict[str, str]]:
    """Contiguous half-open [after, before) windows covering [start, end].

    Consecutive windows share a boundary (prev['before'] == next['after']) so there
    are no gaps and no overlaps. Used to inject after:/before: into Google News.
    """
    start_d = _as_date(start)
    end_d = _as_date(end)
    if end_d <= start_d:
        return [{"after": start_d.isoformat(), "before": end_d.isoformat()}] if end_d == start_d else []

    ranges: List[Dict[str, str]] = []
    cur = start_d
    while cur < end_d:
        if mode == "weekly":
            nxt = cur + timedelta(days=7)
        elif mode == "daily":
            nxt = cur + timedelta(days=1)
        elif mode == "none":
            nxt = end_d
        else:  # monthly (default)
            nxt = _first_of_next_month(cur)
        if nxt > end_d:
            nxt = end_d
        ranges.append({"after": cur.isoformat(), "before": nxt.isoformat()})
        cur = nxt
    return ranges


def matches_or_filter(text: str, keywords: List[str]) -> bool:
    """Comma-separated OR keyword filter: keep if ANY keyword is present."""
    if not keywords:
        return True
    hay = (text or "").lower()
    return any(kw.strip().lower() in hay for kw in keywords if kw.strip())


def parse_or_keywords(raw: str) -> List[str]:
    """Accept a comma-separated OR keyword string."""
    return [k.strip() for k in (raw or "").split(",") if k.strip()]


def parse_feed(xml_text: str) -> List[Dict[str, str]]:
    """Parse RSS/Atom into normalized entries via feedparser."""
    import feedparser

    parsed = feedparser.parse(xml_text)
    out: List[Dict[str, str]] = []
    for e in parsed.entries:
        published = ""
        if getattr(e, "published", None):
            published = e.published
        elif getattr(e, "updated", None):
            published = e.updated
        # Normalize published to ISO date if parseable.
        pub_iso = published
        if getattr(e, "published_parsed", None):
            try:
                pub_iso = datetime(*e.published_parsed[:6]).date().isoformat()
            except Exception:
                pub_iso = published
        out.append(
            {
                "title": getattr(e, "title", "") or "",
                "link": getattr(e, "link", "") or "",
                "summary": getattr(e, "summary", "") or getattr(e, "description", "") or "",
                "published": pub_iso,
                "source": (getattr(getattr(e, "source", None), "title", "") or ""),
                # The outlet's own homepage URL (e.g. https://www.nst.com.my). Reliable
                # geography signal even when the article link is an obfuscated GN redirect.
                "source_url": (getattr(getattr(e, "source", None), "href", "") or ""),
            }
        )
    return out


def inject_date_range(google_news_url: str, after: str, before: str) -> str:
    """Add after:/before: operators to a Google News search feed URL's q param."""
    parsed = urlparse(google_news_url)
    qs = parse_qs(parsed.query)
    q = qs.get("q", [""])[0]
    # Remove any pre-existing date operators, then append fresh ones.
    q = " ".join(tok for tok in q.split() if not tok.startswith(("after:", "before:")))
    q = f"{q} after:{after} before:{before}".strip()
    qs["q"] = [q]
    new_query = "&".join(
        f"{k}={quote_plus(v[0], safe=':')}" if k == "q" else f"{k}={v[0]}" for k, v in qs.items()
    )
    return urlunparse(parsed._replace(query=new_query))


def is_google_news_url(url: str) -> bool:
    return "news.google.com" in (url or "")


def decode_google_news_url(url: str) -> Optional[str]:
    """Best-effort recovery of the publisher URL encoded in a Google News RSS link.

    Google News article links look like .../rss/articles/CBMi<base64>… . The real
    publisher URL is often embedded (base64) in that token. This is inherently
    fragile (Google changes it), so it is strictly best-effort and never trusted
    blindly — callers fall back to redirect-following and honest failure.
    """
    import base64
    import re as _re

    m = _re.search(r"/(?:rss/)?articles/([A-Za-z0-9_\-]+)", url or "")
    if not m:
        return None
    token = m.group(1)
    try:
        raw = base64.urlsafe_b64decode(token + "=" * (-len(token) % 4))
    except Exception:
        return None
    text = raw.decode("latin-1", errors="ignore")
    found = _re.search(r"https?://[^\s\x00-\x1f\"'\\<>]+", text)
    if not found:
        return None
    cand = found.group(0)
    return None if "news.google" in cand else cand


def extract_publisher_link(html: str) -> Optional[str]:
    """Pull the outbound publisher link from a Google News interstitial page."""
    import re as _re

    from bs4 import BeautifulSoup

    mm = _re.search(r'url=(https?://[^"\'>\s]+)', html or "", _re.I)
    if mm and "google" not in mm.group(1):
        return mm.group(1)
    soup = BeautifulSoup(html or "", "html.parser")
    a = soup.find("a", href=True)
    if a and a["href"].startswith("http") and "google" not in a["href"]:
        return a["href"]
    return None


def resolve_and_fetch(link: str, fetch) -> tuple:
    """Return (resolved_url, html). For Google News links, resolve to the publisher
    page first (decode -> redirect -> interstitial parse); for normal links, one fetch.
    Returns (None, None) on failure so the caller falls back honestly."""
    if not is_google_news_url(link):
        r = fetch(link)
        if getattr(r, "status_code", 200) >= 400:
            return None, None
        return getattr(r, "url", link) or link, getattr(r, "text", "") or ""

    # Google News redirect link.
    pub = decode_google_news_url(link)
    if pub:
        try:
            r = fetch(pub)
            if getattr(r, "status_code", 200) < 400:
                return getattr(r, "url", pub) or pub, getattr(r, "text", "") or ""
        except Exception:
            pass
    try:
        r = fetch(link)
        final = getattr(r, "url", link) or link
        html = getattr(r, "text", "") or ""
        if not is_google_news_url(final):
            return final, html
        pl = extract_publisher_link(html)
        if pl:
            try:
                r2 = fetch(pl)
                if getattr(r2, "status_code", 200) < 400:
                    return getattr(r2, "url", pl) or pl, getattr(r2, "text", "") or ""
            except Exception:
                pass
        return final, html  # last resort — may still be the interstitial
    except Exception:
        return None, None


def market_signal(haystack: str, domain: str, market_terms: List[str], cctld: str) -> bool:
    """True if there's evidence the item is in-market. With no market config, always
    True (no filtering). Country name matches its demonym via substring."""
    if not market_terms and not cctld:
        return True
    hay = (haystack or "").lower()
    for t in market_terms:
        if t and t.lower() in hay:
            return True
    if cctld and domain and domain.lower().endswith(cctld.lower()):
        return True
    return False


def summary_echoes_title(title: str, summary: str) -> bool:
    """True when the feed summary is basically just the headline (no real content)."""
    from bs4 import BeautifulSoup

    text = BeautifulSoup(summary or "", "html.parser").get_text(" ", strip=True)
    t = (title or "").strip().lower()
    s = text.strip().lower()
    if not s:
        return True
    return s == t or (t and t in s and len(s) <= len(t) + 15)


